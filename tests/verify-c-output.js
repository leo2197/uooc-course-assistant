const assert = require('node:assert/strict');
const { verifyCOutput, evaluate } = require('../utils/c-output');
assert.equal(evaluate('012 + 3 * (7 / 2)', {}), 19n);
assert.equal(evaluate('-7 / 2', {}), -3n);
assert.equal(evaluate('-7 % 2', {}), -1n);
const verify = (code, choices) => verifyCOutput('程序输出是什么？\n' + code, choices);
assert.deepEqual(verify('int x=012; printf("%d",x);', ['A.12','D.10']).answers, ['D']);
assert.deepEqual(verify('int x=102,y=012;printf("%2d,%2d\\n",x,y);',['A.02,12','D.102,10']).answers,['D']);
assert.deepEqual(verify('int x=2;printf("[%3d]",x);',['A.[  2]','B.[002]']).answers,['A']);
assert.equal(verify('int x=2;printf("%02d",x);',['A.02']),null);
assert.deepEqual(verify('int x=1,y=3; x++; ++y; printf("%d,%d,%d",x,y,7/2);', ['C.2,4,3','A.1,3,3']).answers, ['C']);
assert.deepEqual(verify('int x=0x12; printf("%% %o %X",x,x);', ['B.% 22 12','A.18']).answers, ['B']);
assert.equal(verify('int x=1;printf("%d,%d",x++,++x);', ['A.1,3']),null);
assert.equal(verify('int x=2147483647; x++;printf("%d",x);', ['A.-2147483648']),null);
assert.equal(verify('int x=08;printf("%d",x);', ['A.8']),null);
assert.equal(verify('if(0){int x=012;printf("%d",x);}', ['A.10']),null);
assert.equal(verify('int x=1; printf("%u",x);', ['A.%u']),null);
assert.equal(verify('int x=1; printf("%d",x); printf("%f",2.0);', ['A.1']),null);
assert.equal(verify('int x=1; printf("%d",x);', ['A.1','B.1']),null);
assert.equal(verify('int x=1; system("echo hi");printf("%d",x);', ['A.1']),null);
console.log('PASS defined C integer output, octal, precedence, division, standalone increment; undefined/unsupported cases rejected');
